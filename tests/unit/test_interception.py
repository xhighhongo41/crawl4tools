"""Tests for the detection of responses broken by a TLS-intercepting proxy."""

from __future__ import annotations

import dataclasses
from typing import Any

import pytest

from crawl4tools.engine.interception import (
    Interference,
    InterferenceSign,
    detect_interference,
    is_tls_message,
)

SQUID_TITLE = "ERROR: The requested URL could not be retrieved"


def squid_page(code: str | None = "ERR_SECURE_CONNECT_FAIL", title: str = SQUID_TITLE) -> str:
    """Return an error page shaped like Squid's stock templates."""
    body = f"<body id={code}>" if code is not None else "<body>"
    return (
        '<!DOCTYPE html PUBLIC "-//W3C//DTD HTML 4.01//EN">\n'
        "<html><head>\n"
        '<meta http-equiv="Content-Type" content="text/html; charset=utf-8">\n'
        f"<title>{title}</title>\n"
        "</head>"
        f"{body}\n"
        "<div id=titles><h1>ERROR</h1></div>\n"
        "</body></html>"
    )


ORDINARY_PAGE = "<html><head><title>Example Domain</title></head><body>Hi</body></html>"


