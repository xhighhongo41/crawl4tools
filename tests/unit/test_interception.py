# --- S2: an error page generated by the proxy --------------------------------------


@pytest.mark.parametrize(
    ("headers", "status_code"),
    [
        ({"X-Squid-Error": "ERR_SECURE_CONNECT_FAIL 0"}, 503),
        ({"x-squid-error": "ERR_SECURE_CONNECT_FAIL 0"}, 503),
        ({"X-SQUID-ERROR": "ERR_SECURE_CONNECT_FAIL 0"}, None),
        ({"X-Squid-Error": "ERR_SECURE_CONNECT_FAIL 0"}, 200),
    ],
    ids=["canonical-name", "lowercase-name", "uppercase-name-unknown-status", "status-200"],
)
def test_squid_error_header_is_a_proxy_error_page(
    headers: dict[str, str], status_code: int | None
) -> None:
    assert detect_interference(headers, "", status_code) == Interference(
        InterferenceSign.PROXY_ERROR_PAGE, "ERR_SECURE_CONNECT_FAIL 0"
    )


def test_squid_error_header_detail_is_stripped() -> None:
    found = detect_interference({"X-Squid-Error": "  ERR_CONNECT_FAIL 111 "}, None, 503)
    assert found == Interference(InterferenceSign.PROXY_ERROR_PAGE, "ERR_CONNECT_FAIL 111")


@pytest.mark.parametrize("status_code", [503, 403, 400, 599, None])
def test_squid_title_with_an_error_status_is_a_proxy_error_page(status_code: int | None) -> None:
    found = detect_interference({"content-type": "text/html"}, squid_page(), status_code)
    assert found == Interference(InterferenceSign.PROXY_ERROR_PAGE, "ERR_SECURE_CONNECT_FAIL")


def test_squid_title_without_an_error_code_reports_the_title() -> None:
    found = detect_interference({}, squid_page(code=None), 503)
    assert found == Interference(InterferenceSign.PROXY_ERROR_PAGE, SQUID_TITLE)


def test_squid_title_is_matched_with_normalized_whitespace_and_case() -> None:
    html = squid_page(title="\n  error:   The requested URL\n could NOT be retrieved ")
    found = detect_interference(None, html, 503)
    assert found is not None
    assert found.sign is InterferenceSign.PROXY_ERROR_PAGE


def test_squid_title_with_escaped_characters_is_matched() -> None:
    html = squid_page(title="ERROR:&#32;The requested URL could not be retrieved")
    found = detect_interference(None, html, 503)
    assert found is not None
    assert found.sign is InterferenceSign.PROXY_ERROR_PAGE


@pytest.mark.parametrize("status_code", [200, 204, 301, 399])
def test_squid_title_with_a_success_status_is_not_interference(status_code: int) -> None:
    assert detect_interference({"content-type": "text/html"}, squid_page(), status_code) is None


def test_other_title_with_an_error_status_is_not_interference() -> None:
    assert detect_interference({}, squid_page(title="Service Unavailable"), 503) is None


def test_squid_title_outside_the_title_element_is_not_interference() -> None:
    html = f"<html><head><title>Squid FAQ</title></head><body><p>{SQUID_TITLE}</p></body></html>"
    assert detect_interference({}, html, 503) is None


POLICY_DENIALS = [
    "ERR_ACCESS_DENIED",
    "ERR_CACHE_ACCESS_DENIED",
    "ERR_FORWARDING_DENIED",
    "ERR_CACHE_MGR_ACCESS_DENIED",
]


@pytest.mark.parametrize("code", POLICY_DENIALS)
def test_policy_denial_header_is_not_interference(code: str) -> None:
    # The administrator refused the request: never treat it as a broken proxy.
    headers = {"X-Squid-Error": f"{code} 0"}
    assert detect_interference(headers, squid_page(code=code), 403) is None


@pytest.mark.parametrize("code", POLICY_DENIALS)
def test_policy_denial_header_wins_over_a_non_denial_page(code: str) -> None:
    headers = {"X-Squid-Error": f"{code} 0"}
    assert detect_interference(headers, squid_page(code="ERR_SECURE_CONNECT_FAIL"), 403) is None


@pytest.mark.parametrize("code", POLICY_DENIALS)
def test_policy_denial_header_without_the_status_suffix_is_not_interference(code: str) -> None:
    assert detect_interference({"x-squid-error": code}, None, 403) is None


@pytest.mark.parametrize("code", POLICY_DENIALS)
def test_policy_denial_page_without_the_header_is_not_interference(code: str) -> None:
    # The header can be removed by the administrator; the page still names the error.
    assert detect_interference({}, squid_page(code=code), 403) is None


@pytest.mark.parametrize("value", ["", "   "], ids=["empty-header", "blank-header"])
def test_empty_squid_error_header_falls_back_to_the_title(value: str) -> None:
    headers = {"X-Squid-Error": value}
    assert detect_interference(headers, ORDINARY_PAGE, 503) is None
    found = detect_interference(headers, squid_page(), 503)
    assert found == Interference(InterferenceSign.PROXY_ERROR_PAGE, "ERR_SECURE_CONNECT_FAIL")


# --- S3: a bot challenge ---------------------------------------------------------------


@pytest.mark.parametrize(
    "headers",
    [
        {"cf-mitigated": "challenge"},
        {"CF-Mitigated": "challenge"},
        {"CF-MITIGATED": "Challenge"},
        {"cf-mitigated": "  challenge "},
    ],
    ids=["lowercase", "canonical-name", "uppercase-name-and-value", "padded-value"],
)
def test_cloudflare_challenge_header_is_a_bot_challenge(headers: dict[str, str]) -> None:
    found = detect_interference(headers, "<html><title>Just a moment...</title></html>", 403)
    assert found == Interference(InterferenceSign.BOT_CHALLENGE, "challenge")


def test_cloudflare_challenge_header_is_found_whatever_the_status() -> None:
    found = detect_interference({"cf-mitigated": "challenge"}, None, None)
    assert found == Interference(InterferenceSign.BOT_CHALLENGE, "challenge")


def test_other_cf_mitigated_value_is_not_interference() -> None:
    assert detect_interference({"cf-mitigated": "something-else"}, None, 403) is None


